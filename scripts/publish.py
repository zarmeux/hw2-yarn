#!/usr/bin/env python3
"""Generate authenticated read-only nginx frontends, preserving credentials/cert."""
import grp
import ipaddress
import json
import os
import pathlib
import secrets
import socket
import subprocess
import sys
public,user,edge,nn,snn,*workers=sys.argv[1:]
base=pathlib.Path('/etc/nginx/hw2')
os.umask(0o077)
secret=base/'access.json'
if secret.exists():
    auth=json.loads(secret.read_text())
    if auth['username']!=user or auth['host']!=public:
        raise SystemExit('Changed UI user/host: explicitly migrate existing credentials/certificate first.')
else:
    auth={'username':user,'password':secrets.token_urlsafe(24),'host':public}
    secret.write_text(json.dumps(auth,indent=2)+'\n')
    hashed=subprocess.check_output(['openssl','passwd','-6','-stdin'],input=(auth['password']+'\n').encode()).decode().strip()
    (base/'htpasswd').write_text(user+':'+hashed+'\n')
    (base/'access.netrc').write_text(f"machine {public} login {user} password {auth['password']}\n")
    os.chmod(base/'htpasswd',0o640)
    os.chown(base/'htpasswd',0,grp.getgrnam('www-data').gr_gid)
    # nginx workers need traverse permission; other files stay root-only.
os.chmod(base,0o750)
os.chown(base,0,grp.getgrnam('www-data').gr_gid)
cert=base/'server.crt'; key=base/'server.key'
if not cert.exists():
    try: ipaddress.ip_address(public); san='IP:'+public
    except ValueError: san='DNS:'+public
    subprocess.run(['openssl','req','-x509','-newkey','rsa:2048','-nodes','-days','365',
      '-keyout',str(key),'-out',str(cert),'-subj','/CN='+public,
      '-addext','subjectAltName='+san,'-addext','basicConstraints=critical,CA:FALSE'],check=True,stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
    os.chmod(key,0o600); os.chmod(cert,0o644)
services=[('ResourceManager',edge,8088,8443),('NameNode',nn,9870,8444),
          ('SecondaryNameNode',snn,9868,8445),('JobHistory',edge,19888,8446)]
for n,ip in enumerate(workers,1):
    services.extend([(f'DataNode-{n}',ip,9864,8450+n),(f'NodeManager-{n}',ip,8042,8460+n)])
conf=['# Generated by HW2 scripts. Credentials/private TLS key are outside the repository.']
local_ports={8443:18088,8444:19870,8445:19868,8446:19889,
             8451:19864,8452:19865,8453:19866,8461:18042,8462:18043,8463:18044}
# NameNode builds DataNode links in JavaScript using the RPC hostname, not
# the hostname from infoAddr. Rewriting JSON addresses alone is insufficient.
nn_js=subprocess.check_output(['curl','-fsS','--max-time','10',f'http://{nn}:9870/dfshealth.js']).decode()
anchor='if (n.adminState === "In Service") {'
if nn_js.count(anchor)!=1:
    raise SystemExit('Unsupported NameNode UI: expected one DataNode link injection anchor.')
for mode in ('external','ssh'):
    dn_urls={}
    for _,target_ip,target_up,target_port in services:
        if target_up!=9864:
            continue
        url=f'https://{public}:{target_port}' if mode=='external' else f'http://127.0.0.1:{local_ports[target_port]}'
        aliases={target_ip,socket.getfqdn(target_ip)}
        aliases |= {a.split('.')[0] for a in list(aliases) if not a[0].isdigit()}
        for alias in aliases:
            dn_urls[alias]=url
    injection='n.dnWebAddress = '+json.dumps(dn_urls,sort_keys=True)+'[n.name.split(":")[0]] || n.dnWebAddress;\n          '+anchor
    patched=nn_js.replace(anchor,injection)
    # nginx substitutions are literal strings; use a single narrowly targeted
    # override for the NameNode asset rather than editing Hadoop's installation.
    (base/f'dfshealth-{mode}.js').write_text(patched)
    os.chmod(base/f'dfshealth-{mode}.js',0o644)
for name,ip,up,port in services:
  for mode in ('external','ssh'):
    if mode=='external':
        listener=f'listen {port} ssl;'
        security=f'''ssl_certificate {cert};
 ssl_certificate_key {key};
 ssl_protocols TLSv1.2 TLSv1.3;
 auth_basic "team-34 Hadoop read-only";
 auth_basic_user_file {base}/htpasswd;'''
        scheme='https'
    else:
        listener=f'listen 127.0.0.1:{local_ports[port]};'
        security='# Local SSH frontend: reachable only from edge loopback. SSH authenticates clients.'
        scheme='http'
    conf.append(f'''server {{
 {listener}
 server_name {public};
 {security}
 add_header X-Content-Type-Options nosniff always;
 add_header Referrer-Policy same-origin always;
''')
    if name=='NameNode':
        conf.append(f''' location = /dfshealth.js {{
  alias {base}/dfshealth-{mode}.js;
  default_type application/javascript;
  add_header Cache-Control "no-cache";
  limit_except GET HEAD {{ deny all; }}
 }}''')
    conf.append(f'''
 location / {{
  limit_except GET HEAD {{ deny all; }}
  proxy_pass http://{ip}:{up};
  proxy_set_header Host {ip}:{up};
  proxy_set_header Authorization "";
  proxy_set_header X-Forwarded-Proto {scheme};
  proxy_set_header X-Forwarded-For $remote_addr;
  proxy_set_header Accept-Encoding "";
  proxy_connect_timeout 5s;
  proxy_read_timeout 30s;
  sub_filter_once off;
  sub_filter_types application/json application/javascript text/javascript text/plain;
''')
    for _,target_ip,target_up,target_port in services:
        aliases={target_ip,socket.getfqdn(target_ip)}
        aliases |= {a.split('.')[0] for a in list(aliases) if not a[0].isdigit()}
        for alias in sorted(aliases):
            old=f'{alias}:{target_up}'
            new=f'{public}:{target_port}' if mode=='external' else f'127.0.0.1:{local_ports[target_port]}'
            conf.extend([f'  proxy_redirect http://{old}/ {scheme}://{new}/;',
                         f"  sub_filter 'http://{old}' '{scheme}://{new}';",
                         f"  sub_filter '{old}' '{new}';"])
    conf.append(' }\n}')
pathlib.Path('/etc/nginx/conf.d/hw2.conf').write_text('\n'.join(conf)+'\n')
(base/'endpoints.json').write_text(json.dumps([{'service':name,'upstream':f'http://{ip}:{up}',
                'url':f'https://{public}:{port}/','ssh_url':f'http://127.0.0.1:{local_ports[port]}/'}
                for name,ip,up,port in services],indent=2)+'\n')
(base/'.managed').touch()
